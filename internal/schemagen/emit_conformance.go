// conformanceFile emits a test file that round-trips a fully populated
// sample of every top-level type through XML plist, binary plist (encoded
// by an independent library) and JSON, and checks the registry.
func (e *emitter) conformanceFile() []byte {
	b := buf()
	b.WriteString("// Code generated by admgen; DO NOT EDIT.\n")
	fmt.Fprintf(b, "// Source: apple/device-management@%s\n\n", e.opts.Commit)
	fmt.Fprintf(b, "package %s_test\n\n", e.pkg.Name)
	needTime := false
	for _, td := range e.pkg.Types {
		for _, f := range td.Fields {
			if strings.Contains(f.GoType, "time.Time") {
				needTime = true
			}
		}
	}
	b.WriteString("import (\n\t\"testing\"\n")
	if needTime {
		b.WriteString("\t\"time\"\n")
	}
	fmt.Fprintf(
		b,
		"\n\t\"%s/schema/internal/conformance\"\n\t\"%s/schema/%s\"\n)\n\n",
		ModulePath,
		ModulePath,
		e.pkg.Name,
	)
	if needTime {
		b.WriteString("var sampleTime = time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC)\n\n")
	}
	for _, td := range e.pkg.Types {
		e.sampleFunc(b, td)
	}
	jsonOnly := e.pkg.Family == FamilyStatus || e.pkg.Family == FamilyDDM ||
		e.pkg.Family == FamilyDDMProto
	fmt.Fprintf(b, "func TestConformanceRoundTrip(t *testing.T) {\n\tt.Parallel()\n")
	for _, st := range e.pkg.Schemas {
		for _, td := range []*TypeDef{st.Request, st.Response} {
			if td == nil {
				continue
			}
			fmt.Fprintf(b, "\tt.Run(%q, func(t *testing.T) {\n\t\tt.Parallel()\n", td.Name)
			fmt.Fprintf(
				b,
				"\t\tconformance.RoundTrip(t, sample%s(0), func() any { return new(%s.%s) }, %t)\n",
				td.Name,
				e.pkg.Name,
				td.Name,
				jsonOnly,
			)
			b.WriteString("\t})\n")
		}
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(b, "func TestConformanceValidate(t *testing.T) {\n\tt.Parallel()\n")
	for _, st := range e.pkg.Schemas {
		for _, td := range []*TypeDef{st.Request, st.Response} {
			if td == nil {
				continue
			}
			fmt.Fprintf(
				b,
				"\tconformance.Validates(t, %q, sample%s(0), new(%s.%s))\n",
				td.Name,
				td.Name,
				e.pkg.Name,
				td.Name,
			)
		}
	}
	b.WriteString("}\n\n")

	iface, method := e.familyInterface(), e.identifierMethod()
	fmt.Fprintf(b, "func TestConformanceRegistry(t *testing.T) {\n\tt.Parallel()\n")
	fmt.Fprintf(
		b,
		"\tif len(%s.Registry) != %d {\n\t\tt.Fatalf(\"registry has %%d entries, want %d\", len(%s.Registry))\n\t}\n",
		e.pkg.Name,
		len(e.registryEntries()),
		len(e.registryEntries()),
		e.pkg.Name,
	)
	fmt.Fprintf(
		b,
		"\tfor name, en := range %s.Registry {\n\t\tv := en.New()\n\t\tif v == nil || v.%s() != en.ID || v.SchemaPath() != en.Schema {\n",
		e.pkg.Name,
		method,
	)
	b.WriteString("\t\t\tt.Errorf(\"registry entry %q is inconsistent: %+v\", name, en)\n\t\t}\n")
	fmt.Fprintf(b, "\t\tvar _ %s.%s = v\n", e.pkg.Name, iface)
	fmt.Fprintf(
		b,
		"\t\tfound := false\n\t\tfor _, x := range %s.ByID(en.ID) {\n\t\t\tif x.Schema == en.Schema {\n\t\t\t\tfound = true\n\t\t\t}\n\t\t}\n\t\tif !found {\n\t\t\tt.Errorf(\"ByID(%%q) does not contain %%s\", en.ID, name)\n\t\t}\n",
		e.pkg.Name,
	)
	if e.pkg.Family == FamilyCommands {
		b.WriteString(
			"\t\tif r := en.NewResponse(); r == nil || r.ResponseRequestTypeName() != en.ID {\n\t\t\tt.Errorf(\"response for %q is inconsistent\", name)\n\t\t}\n",
		)
	}
	b.WriteString("\t}\n")
	fmt.Fprintf(
		b,
		"\tif ids := %s.IDs(); len(ids) == 0 || len(ids) > len(%s.Registry) {\n\t\tt.Errorf(\"IDs() = %%d\", len(ids))\n\t}\n",
		e.pkg.Name,
		e.pkg.Name,
	)
	fmt.Fprintf(
		b,
		"\tif len(%s.ByID(\"no-such-id\")) != 0 {\n\t\tt.Error(\"ByID(no-such-id) should be empty\")\n\t}\n",
		e.pkg.Name,
	)
	fmt.Fprintf(
		b,
		"\tif %s.Support(\"nope\") != nil {\n\t\tt.Error(\"Support(nope) should be nil\")\n\t}\n",
		e.pkg.Name,
	)
	for _, st := range e.pkg.Schemas {
		fmt.Fprintf(
			b,
			"\tif %s.Support(%q) == nil {\n\t\tt.Error(\"missing support entry for %s\")\n\t}\n",
			e.pkg.Name,
			st.Name,
			st.Name,
		)
	}
	b.WriteString("}\n")
	e.reasonsConformance(b)
	return b.Bytes()
}

// reasonsConformance emits the test that pins the reason vocabulary: the
// constants and the map are one set, so a caller may treat the map as the
// bound on what a device can report.
func (e *emitter) reasonsConformance(b *bytes.Buffer) {
	decls := e.reasons()
	if len(decls) == 0 {
		return
	}
	codes := reasonCodes(decls)
	pkg := e.pkg.Name
	fmt.Fprintf(b, "\nfunc TestConformanceReasons(t *testing.T) {\n\tt.Parallel()\n")
	fmt.Fprintf(b, "\tconsts := []string{\n")
	for _, code := range codes {
		fmt.Fprintf(b, "\t\t%s.%s,\n", pkg, reasonConstName(code))
	}
	b.WriteString("\t}\n")
	fmt.Fprintf(b, "\tif len(%s.Reasons) != %d {\n\t\tt.Fatalf(\"Reasons has %%d codes, want %d\", len(%s.Reasons))\n\t}\n",
		pkg, len(codes), len(codes), pkg)
	fmt.Fprintf(b, "\tfor _, code := range consts {\n\t\tif _, ok := %s.Reasons[code]; !ok {\n\t\t\tt.Errorf(\"constant %%q is not in Reasons\", code)\n\t\t}\n\t}\n", pkg)
	fmt.Fprintf(b, "\tfor code, entries := range %s.Reasons {\n\t\tif len(entries) == 0 {\n\t\t\tt.Errorf(\"%%q has no entries\", code)\n\t\t}\n", pkg)
	b.WriteString("\t\tfor _, en := range entries {\n\t\t\tif en.Code != code || en.Schema == \"\" || en.Description == \"\" {\n\t\t\t\tt.Errorf(\"entry for %q is incomplete: %+v\", code, en)\n\t\t\t}\n")
	b.WriteString("\t\t\tfor _, d := range en.Details {\n\t\t\t\tif d.Key == \"\" || d.Type == \"\" {\n\t\t\t\t\tt.Errorf(\"detail of %q is incomplete: %+v\", code, d)\n\t\t\t\t}\n\t\t\t}\n\t\t}\n\t}\n")
	fmt.Fprintf(b, "\tgot := %s.ReasonCodes()\n\tif len(got) != len(consts) {\n\t\tt.Fatalf(\"ReasonCodes() = %%d, want %%d\", len(got), len(consts))\n\t}\n", pkg)
	b.WriteString("\tfor i, code := range got {\n\t\tif code != consts[i] {\n\t\t\tt.Errorf(\"ReasonCodes()[%d] = %q, want %q\", i, code, consts[i])\n\t\t}\n\t}\n")
	fmt.Fprintf(b, "\tif _, ok := %s.Reasons[\"Error.NoSuchReason\"]; ok {\n\t\tt.Error(\"Reasons contains a code Apple does not declare\")\n\t}\n}\n", pkg)
}

// sampleDepth bounds sample nesting. Apple's deepest non-recursive
// structures are a few levels; recursive ones (bookmark folders, home screen
// pages) cut off through nil slices once this depth is reached.
const sampleDepth = 12

// sampleFunc emits sampleT(depth int) *T returning a value with every field
// populated.
func (e *emitter) sampleFunc(b *bytes.Buffer, td *TypeDef) {
	fmt.Fprintf(
		b,
		"func sample%s(d int) *%s.%s {\n\tif d > %d {\n\t\treturn nil\n\t}\n\t_ = d\n\treturn &%s.%s{\n",
		td.Name,
		e.pkg.Name,
		td.Name,
		sampleDepth,
		e.pkg.Name,
		td.Name,
	)
	for _, f := range td.Fields {
		fmt.Fprintf(b, "\t\t%s: %s,\n", f.Name, e.sampleValue(f))
	}
	b.WriteString("\t}\n}\n\n")
}

func (e *emitter) sampleValue(f *Field) string {
	if f.Pointer {
		if f.Kind == KindStruct {
			return "sample" + f.Base + "(d + 1)"
		}
		return "new(" + e.sampleBase(f, f.Base) + ")"
	}
	return e.sampleOf(f)
}

// sampleOf returns a non-pointer sample expression for a field or element.
func (e *emitter) sampleOf(f *Field) string {
	switch f.Kind {
	case KindStruct:
		return "conformance.Deref(sample" + f.Base + "(d + 1))"
	case KindArray:
		return e.sampleArray(f)
	case KindMap:
		if f.Elem == nil {
			return `map[string]any{"k": "v"}`
		}
		return "map[string]" + e.qualify(f.Elem.GoType) + `{"k": ` + e.sampleOf(f.Elem) + "}"
	case KindScalar:
	}
	return e.sampleBase(f, f.Base)
}

func (e *emitter) sampleArray(f *Field) string {
	if len(f.Variants) > 0 {
		parts := make([]string, 0, len(f.Variants))
		for _, v := range f.Variants {
			// Values, not pointers: plist encoders reject pointers inside any.
			parts = append(parts, "conformance.Deref(sample"+v.Name+"(d + 1))")
		}
		return "[]any{" + strings.Join(parts, ", ") + "}"
	}
	if f.Elem == nil {
		// Element type came from a recursion fixup rather than a subkey.
		switch {
		case f.Base == "any":
			return `[]any{"x"}`
		case strings.HasPrefix(f.Base, "[]"):
			return "nil"
		}
		return fmt.Sprintf("conformance.SliceOf(sample%s(d + 1))", f.Base)
	}
	el := f.Elem
	switch el.Kind {
	case KindStruct:
		return fmt.Sprintf("conformance.SliceOf(sample%s(d + 1))", el.Base)
	case KindArray, KindMap:
		return "[]" + e.qualify(el.GoType) + "{" + e.sampleOf(el) + "}"
	case KindScalar:
	}
	return "[]" + e.qualify(el.GoType) + "{" + e.sampleBase(el, el.Base) + "}"
}

// qualify prefixes generated struct names with the package name for use
// from the external test package.
func (e *emitter) qualify(goType string) string {
	base := strings.TrimLeft(goType, "[]*")
	if !e.pkg.used[base] {
		return goType
	}
	return goType[:len(goType)-len(base)] + e.pkg.Name + "." + base
}

// sampleBase returns a scalar literal, preferring the first rangelist value
// so generated samples also pass validation.
func (e *emitter) sampleBase(f *Field, base string) string {
	if f.Src != nil && len(f.Src.RangeList) > 0 {
		switch v := f.Src.RangeList[0].(type) {
		case string:
			if base == "string" {
				return goLiteral(v)
			}
		case int:
			if base == "int64" {
				return "int64(" + fmt.Sprint(v) + ")"
			}
			if base == "float64" {
				return goLiteral(float64(v))
			}
		case float64:
			if base == "float64" {
				return goLiteral(v)
			}
			if base == "int64" {
				return "int64(" + fmt.Sprint(int64(v)) + ")"
			}
		}
	}
	switch base {
	case "string":
		if f.Src != nil && f.Src.Format != "" {
			if s, ok := regexSample(f.Src.Format); ok {
				return goLiteral(s)
			}
		}
		return `"s"`
	case "int64":
		if f.Src != nil && f.Src.Range != nil && f.Src.Range.Min != nil {
			return fmt.Sprintf("int64(%d)", int64(*f.Src.Range.Min))
		}
		return "int64(1)"
	case "float64":
		if f.Src != nil && f.Src.Range != nil && f.Src.Range.Min != nil {
			return goLiteral(*f.Src.Range.Min)
		}
		return "1.5"
	case "bool":
		return "true"
	case "time.Time":
		return "sampleTime"
	case "[]byte":
		return "[]byte{1, 2, 3}"
	case "any":
		return `any("x")`
	}
	return "nil"
}
