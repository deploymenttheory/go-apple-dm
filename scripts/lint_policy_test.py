"""Exercise the real lint configuration against isolated Go sources.

Run with python -m unittest discover -s scripts -p lint_policy_test.py.
No fixture functions execute, and no external modules or services are needed.
"""

import json
import os
from pathlib import Path
import subprocess
import tempfile
import unittest

from lint import ROOT


class LintPolicyTest(unittest.TestCase):
    def test_analysis_boundaries(self):
        with tempfile.TemporaryDirectory(prefix="dm-lint-policy-") as directory:
            root = Path(directory)
            go_version = next(line.split()[1] for line in (ROOT / "go.mod").read_text().splitlines()
                              if line.startswith("go "))
            (root / "go.mod").write_text(f"module example.test/lintpolicy\n\ngo {go_version}\n")
            (root / "valid.go").write_text("package fixture\n\nfunc Value() int { return 1 }\n")
            env = os.environ.copy()
            env.update(GOWORK="off", GOFLAGS="", GOPROXY="off")
            linter = os.environ.get("GOLANGCI_LINT", "golangci-lint")
            cases = [
                ("clean", "sample_test.go", "package fixture\n", None),
                ("authored tests", "sample_test.go", '''package fixture

import "os"

func Example() {
	os.Remove("unused-fixture-path")
	// Output:
}
''', "errcheck"),
                ("unexplained suppression", "sample_test.go", '''package fixture

import "os"

func Example() {
	os.Remove("unused-fixture-path") //nolint:errcheck
	// Output:
}
''', "nolintlint"),
                ("unused suppression", "sample_test.go", '''package fixture

//nolint:errcheck // No operation in this function returns an error.
func Example() {
	// Output:
}
''', "nolintlint"),
                ("generated diagnostics", "generated.go", '''// Code generated by lint policy fixture. DO NOT EDIT.

package fixture

import "os"

func Generated() { os.Remove("unused-fixture-path") }
''', None),
                ("generated compilation", "generated.go", '''// Code generated by lint policy fixture. DO NOT EDIT.

package fixture

func Generated() { missingSymbol() }
''', "typecheck"),
            ]
            for name, filename, source, expected in cases:
                with self.subTest(name=name):
                    for old in ("sample_test.go", "generated.go", "result.json"):
                        (root / old).unlink(missing_ok=True)
                    (root / filename).write_text(source)
                    result = subprocess.run(
                        [linter, "run", "--fix=false", "--config=" + str(ROOT / ".golangci.yml"),
                         "--output.json.path=" + str(root / "result.json"), "./..."],
                        cwd=root, env=env, text=True, capture_output=True, timeout=120)
                    report = root / "result.json"
                    issues = (json.loads(report.read_text()).get("Issues") or []) if report.exists() else []
                    diagnostics = result.stdout + result.stderr
                    if expected is None:
                        self.assertEqual(result.returncode, 0, diagnostics)
                    else:
                        self.assertNotEqual(result.returncode, 0, diagnostics)
                        if expected == "typecheck":
                            self.assertIn("missingSymbol", diagnostics)
                        else:
                            self.assertIn(expected, {issue["FromLinter"] for issue in issues}, diagnostics)


if __name__ == "__main__":
    unittest.main()
